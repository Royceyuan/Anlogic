STATE = ("主板：总览", "主板：自动讲解", "主板：手动看图", "主板：自动讲解（暂停）")


def build_font():
    texts = list(LEFT.values()) + list(RIGHT.values()) + list(LINK) + list(STATE)
    chars = " " + "".join(sorted(set("".join(texts)) - {" "}))
    assert len(chars) <= 256, "fixed font exceeds eight BRAM32K banks"
    ids = {char: i for i, char in enumerate(chars)}
    cjk = ImageFont.truetype("C:/Windows/Fonts/msyh.ttc", 28)
    ascii_font = ImageFont.truetype("C:/Windows/Fonts/consola.ttf", 24)
    glyphs = []
    for char in chars:
        tile = Image.new("L", (32, 32))
        font = cjk if ord(char) > 127 else ascii_font
        width = 32 if ord(char) > 127 else 16
        box = font.getbbox(char, anchor="ls")
        assert box[2] - box[0] <= width and box[3] + 26 <= 32
        ImageDraw.Draw(tile).text((2 if width == 32 else 1, 26), char,
                                 font=font, fill=255, anchor="ls")
        # Two 16-bit words per native row, left half then right half.
        words = [sum((tile.getpixel((half*16+x, y)) >= 128) << (15-x)
                     for x in range(16)) for y in range(32) for half in range(2)]
        glyphs.append(words)

    def cells(text):
        result = []
        for char in text:
            result.append(ids[char])
            if ord(char) > 127:
                result.append(ids[char] | 256)
        assert len(result) <= 32, f"column exceeds 512 pixels: {text}"
        return result

    def packed(text):
        return sum(code << (9*i) for i, code in enumerate(cells(text)))

    banks = (len(chars) + 31) // 32
    output = ["// Generated by scripts/generate_help_font.py; do not hand-edit.",
              f"localparam integer HELP_FONT_BANKS = {banks};",
              "function [287:0] help_line;",
              "input [4:0] line; input side; input [1:0] main_context;",
              "input paused; input [1:0] link; begin help_line=0;",
              "if (line == 20) begin if (!side) case(link)"]
    output += [f"{i}:help_line=288'h{packed(text):072x};" for i, text in enumerate(LINK)]
    output += ["default:help_line=0; endcase else case(main_context)",
               f"0:help_line=288'h{packed(STATE[0]):072x};",
               f"2:help_line=288'h{packed(STATE[2]):072x};",
               f"default:help_line=paused ? 288'h{packed(STATE[3]):072x} : 288'h{packed(STATE[1]):072x};",
               "endcase end else if (!side) case(line)"]
    output += [f"{row}:help_line=288'h{packed(text):072x};" for row, text in LEFT.items()]
    output += ["default:help_line=0; endcase else case(line)"]
    output += [f"{row}:help_line=288'h{packed(text):072x};" for row, text in RIGHT.items()]
    output += ["default:help_line=0; endcase end endfunction",
               "function [255:0] help_font_init; input integer chunk; begin case(chunk)"]
    for code, words in enumerate(glyphs):
        for chunk in range(4):
            value = sum(word << (16*i) for i, word in enumerate(words[chunk*16:chunk*16+16]))
            output.append(f"{code*4+chunk}:help_font_init=256'h{value:064x};")
    output += ["default:help_font_init=0; endcase end endfunction"]
    (ROOT / "src/secondary/secondary_help_font.vh").write_text("\n".join(output)+"\n", encoding="utf-8")
    return ids, glyphs, banks, cells


if __name__ == "__main__":
    ids, _, banks, _ = build_font()
    print(f"PASS help font: {len(ids)} glyphs, {banks} BRAM32K banks")
