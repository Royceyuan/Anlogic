def build_font():
    texts = list(LEFT.values()) + list(RIGHT.values()) + list(LINK) + list(STATE)
    chars = " " + "".join(sorted(set("".join(texts)) - {" "}))
    assert len(chars) <= 256, "fixed font exceeds eight BRAM32K banks"
    ids = {char: i for i, char in enumerate(chars)}
    cjk = ImageFont.truetype("C:/Windows/Fonts/msyh.ttc", 28)
    ascii_font = ImageFont.truetype("C:/Windows/Fonts/consola.ttf", 24)
    glyphs = []
    for char in chars:
        tile = Image.new("L", (32, 32))
        font = cjk if ord(char) > 127 else ascii_font
        width = 32 if ord(char) > 127 else 16
        box = font.getbbox(char, anchor="ls")
        assert box[2] - box[0] <= width and box[3] + 26 <= 32
        ImageDraw.Draw(tile).text((2 if width == 32 else 1, 26), char,
                                 font=font, fill=255, anchor="ls")
        # Two 16-bit words per native row, left half then right half.
        words = [sum((tile.getpixel((half*16+x, y)) >= 128) << (15-x)
                     for x in range(16)) for y in range(32) for half in range(2)]
        glyphs.append(words)

    def cells(text):
        result = []
        for char in text:
            result.append(ids[char])
            if ord(char) > 127:
                result.append(ids[char] | 256)
        assert len(result) <= 32, f"column exceeds 512 pixels: {text}"
        return result

    def packed(text):
        return sum(code << (9*i) for i, code in enumerate(cells(text)))

    banks = (len(chars) + 31) // 32
    output = ["// Generated by tools/prepare_secondary_help.py; do not hand-edit.",
              f"localparam integer HELP_FONT_BANKS = {banks};",
              "function [287:0] help_line;",
              "input [4:0] line; input side; input [1:0] main_context;",
              "input paused; input [1:0] link; begin help_line=0;",
              "if (line == 20) begin if (!side) case(link)"]
    output += [f"{i}:help_line=288'h{packed(text):072x};" for i, text in enumerate(LINK)]
    output += ["default:help_line=0; endcase else case(main_context)",
               f"0:help_line=288'h{packed(STATE[0]):072x};",
               f"2:help_line=288'h{packed(STATE[2]):072x};",
               f"default:help_line=paused ? 288'h{packed(STATE[3]):072x} : 288'h{packed(STATE[1]):072x};",
               "endcase end else if (!side) case(line)"]
    output += [f"{row}:help_line=288'h{packed(text):072x};" for row, text in LEFT.items()]
    output += ["default:help_line=0; endcase else case(line)"]
    output += [f"{row}:help_line=288'h{packed(text):072x};" for row, text in RIGHT.items()]
    output += ["default:help_line=0; endcase end endfunction",
               "function [255:0] help_font_init; input integer chunk; begin case(chunk)"]
    for code, words in enumerate(glyphs):
        for chunk in range(4):
            value = sum(word << (16*i) for i, word in enumerate(words[chunk*16:chunk*16+16]))
            output.append(f"{code*4+chunk}:help_font_init=256'h{value:064x};")
    output += ["default:help_font_init=0; endcase end endfunction"]
    (ROOT / "src/secondary/secondary_help_font.vh").write_text("\n".join(output)+"\n", encoding="utf-8")
    return ids, glyphs, banks, cells


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--card", type=Path, help="secondary TF root; add only IMAGEB.BMP")
    args = parser.parse_args()
    ASSETS.mkdir(parents=True, exist_ok=True)
    ids, glyphs, banks, cells = build_font()
    with Image.open(ASSETS / "background_source.png") as image:
        background = ImageOps.fit(image.convert("RGB"), (1280, 720), Image.Resampling.LANCZOS)
        background = Image.blend(Image.new("RGB", (1280, 720), (242, 238, 225)), background, 0.65)
    small = background.resize((160, 90), Image.Resampling.LANCZOS)
    small.save(ASSETS / "IMAGEB.BMP", format="BMP")
    for group in range(4):
        preview = small.resize((1280, 720), Image.Resampling.NEAREST)
        draw = ImageDraw.Draw(preview)
        draw.rectangle((32, 80, 623, 639), fill=(247, 245, 236))
        draw.rectangle((656, 80, 1247, 639), fill=(247, 245, 236))
        draw.rectangle((32, 656, 1247, 703), fill=(229, 234, 225))
        first = 3 + group*3
        draw.rectangle((664, 24+first*32, 1239, 24+(first+3)*32-1), fill=(229, 234, 225))
        for side, texts in enumerate((LEFT, RIGHT)):
            for row in range(21):
                text = texts.get(row, "")
                if row == 20:
                    text = LINK[1] if side == 0 else STATE[0]
                for column, cell in enumerate(cells(text)):
                    words = glyphs[cell & 255]
                    mask = Image.new("1", (16, 32))
                    mask.putdata([(words[y*2+(cell >> 8)] >> (15-x)) & 1
                                  for y in range(32) for x in range(16)])
                    preview.paste((35, 48, 46), (64+side*608+column*16, 24+row*32), mask)
        preview.save(ASSETS / f"preview_group{group}.png")
    bmp = ASSETS / "IMAGEB.BMP"
    assert bmp.stat().st_size == 43254
    metadata = {"file": "IMAGEB.BMP", "size": [160, 90], "bpp": 24,
                "sha256": hashlib.sha256(bmp.read_bytes()).hexdigest(), "glyphs": len(ids),
                "font_banks": banks, "font": "Microsoft YaHei regular 28px / Consolas regular 24px, native 1bpp",
                "layout": "two 512px text columns, 32px line pitch, bottom communication/state strip",
                "background_cache_bytes": 160*90*2,
                "prompt": "16:9 pale ivory museum instruction background; faded bronze ornament at edges; clean blank text area; no lettering",
                "generation": "built-in image_gen; existing artwork reused"}
    (ASSETS / "manifest.json").write_text(json.dumps(metadata, ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    if args.card:
        import shutil
        target = args.card / "IMAGEB.BMP"
        if target.exists() and hashlib.sha256(target.read_bytes()).hexdigest() != metadata["sha256"]:
            raise SystemExit("IMAGEB.BMP already exists with different contents; back it up before replacing")
        shutil.copyfile(bmp, target)
        assert hashlib.sha256(target.read_bytes()).hexdigest() == metadata["sha256"]
    print(json.dumps(metadata, ensure_ascii=False))


if __name__ == "__main__":
    main()
