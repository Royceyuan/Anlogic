def build_font():
    texts = list(COMMON.values()) + [s for group in GROUPS + MAIN for s in group] + list(STATUS)
    assert all(len(s) <= 32 for s in texts), "instruction line exceeds 32 cells"
    chars = " " + "".join(sorted(set("".join(texts)) - {" "}))
    assert len(chars) <= 256
    ids = {char: i for i, char in enumerate(chars)}
    font = ImageFont.truetype("C:/Windows/Fonts/simhei.ttf", 16)
    glyphs = []
    for char in chars:
        tile = Image.new("L", (16, 16))
        ImageDraw.Draw(tile).text((0, 0), char, font=font, fill=255, anchor="lt")
        rows = [sum((tile.getpixel((x, y)) >= 96) << (15 - x) for x in range(16)) for y in range(16)]
        glyphs.append(sum(value << (16 * y) for y, value in enumerate(rows)))
    def packed(text):
        return sum(ids[c] << (8 * i) for i, c in enumerate(text))
    # Generated constants: no full Chinese font or pixel-time division.
    output = ["// Generated by tools/prepare_secondary_help.py; do not hand-edit.",
              "function [255:0] help_line;", "input [4:0] line; input [1:0] group_id;",
              "input [1:0] main_context; input paused; input [1:0] link;", "begin", "help_line=0;", "case(line)"]
    for row, text in COMMON.items():
        output.append(f"{row}:help_line=256'h{packed(text):064x};")
    output += ["2:begin", "case(main_context)",
               f"0:help_line=256'h{packed(STATUS[0]):064x};",
               f"2:help_line=256'h{packed(STATUS[2]):064x};",
               f"default:help_line=paused ? 256'h{packed(STATUS[3]):064x} : 256'h{packed(STATUS[1]):064x};",
               "endcase end"]
    for row in range(3, 6):
        output += [f"{row}:case(group_id)"]
        for group in range(4):
            output.append(f"{group}:help_line=256'h{packed(GROUPS[group][row-3]):064x};")
        output.append("endcase")
    output += ["7:case(link)"]
    for link, text in ((0, STATUS[5]), (1, STATUS[4]), (2, STATUS[6])):
        output.append(f"{link}:help_line=256'h{packed(text):064x};")
    output += ["default:help_line=0; endcase"]
    for row in range(9, 12):
        output += [f"{row}:case(main_context)"]
        for context in range(3):
            output.append(f"{context}:help_line=256'h{packed(MAIN[context][row-9]):064x};")
        output += ["default:help_line=0; endcase"]
    output += ["default:help_line=0; endcase end endfunction", "function [255:0] help_font_init;",
               "input integer code; begin case(code)"]
    output += [f"{i}:help_font_init=256'h{value:064x};" for i, value in enumerate(glyphs)]
    output += ["default:help_font_init=0; endcase end endfunction"]
    (ROOT / "src/secondary/secondary_help_font.vh").write_text("\n".join(output)+"\n", encoding="utf-8")
    return font, ids, glyphs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--card", type=Path, help="secondary TF root; add only IMAGEB.BMP")
    args = parser.parse_args()
    ASSETS.mkdir(parents=True, exist_ok=True)
    font, ids, glyphs = build_font()
    with Image.open(ASSETS / "background_source.png") as image:
        # The generated artwork is already faded; blend once more offline,
        # never add real-time alpha multiplication to the FPGA pixel path.
        background = ImageOps.fit(image.convert("RGB"), (1280, 720), Image.Resampling.LANCZOS)
        background = Image.blend(Image.new("RGB", (1280, 720), (242, 238, 225)), background, 0.65)
    small = background.resize((160, 90), Image.Resampling.LANCZOS)
    small.save(ASSETS / "IMAGEB.BMP", format="BMP")
    # Preview uses precisely the glyph bits and nearest-neighbour backdrop
    # used by the hardware, not a separate typographic mock-up.
    for group in range(4):
        preview = small.resize((1280, 720), Image.Resampling.NEAREST)
        for row in range(18):
            text = COMMON.get(row, "")
            if row == 2: text = STATUS[0]
            if row == 7: text = STATUS[4]
            if 3 <= row <= 5: text = GROUPS[group][row-3]
            if 9 <= row <= 11: text = MAIN[0][row-9]
            for column, char in enumerate(text):
                bits = glyphs[ids[char]]
                mask = Image.new("1", (16, 16))
                mask.putdata([(bits >> (y*16+15-x)) & 1 for y in range(16) for x in range(16)])
                mask = mask.resize((32, 32), Image.Resampling.NEAREST)
                preview.paste((35, 48, 46) if row not in (0, 3, 8) else (91, 69, 37),
                              (64+column*32, 48+row*32), mask)
        preview.save(ASSETS / f"preview_group{group}.png")
    bmp = ASSETS / "IMAGEB.BMP"
    assert bmp.stat().st_size == 43254
    metadata = {"file": "IMAGEB.BMP", "size": [160, 90], "bpp": 24,
                "sha256": hashlib.sha256(bmp.read_bytes()).hexdigest(), "glyphs": len(ids),
                "background_cache_bytes": 160*90*2,
                "prompt": "16:9 pale ivory museum instruction background; faded bronze ornament at edges; clean blank text area; no lettering",
                "generation": "built-in image_gen"}
    (ASSETS / "manifest.json").write_text(json.dumps(metadata, ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    if args.card:
        import shutil
        target = args.card / "IMAGEB.BMP"
        if target.exists() and hashlib.sha256(target.read_bytes()).hexdigest() != metadata["sha256"]:
            raise SystemExit("IMAGEB.BMP already exists with different contents; back it up before replacing")
        shutil.copyfile(bmp, target)
        assert hashlib.sha256(target.read_bytes()).hexdigest() == metadata["sha256"]
    print(json.dumps(metadata, ensure_ascii=False))


if __name__ == "__main__":
    main()
